"""Нормализация текста синонимов.

Синонимы сравниваются не как есть: «Куб. м/час», «куб.м/ч» и «КУБ М/ЧАС» — одно
и то же для сопоставления. Нормализованная форма хранится отдельной колонкой,
уникальность проверяется по ней (schema.sql: `uq_alias_norm_scope`).

Правила намеренно простые и обратимо описуемые: разбор единиц и морфологию
выполняет pipeline, а здесь нужно лишь свести очевидные различия записи.
"""

from __future__ import annotations

import re
import unicodedata

#: Латиница, которую OCR и люди путают с кириллицей: «mм/c» вместо «мм/с»,
#: «Pабота» с латинской P. Без этой замены один и тот же синоним попадал бы в
#: каталог дважды и делал сопоставление неоднозначным.
#:
#: Только строчные буквы: `normalize` сначала приводит регистр, поэтому запись
#: заглавных здесь не сработала бы и создавала бы ложное чувство покрытия.
#: Набор ограничен буквами, неотличимыми в типовых шрифтах — «h»/«н» и «b»/«в»
#: сюда не входят, они лишь отдалённо похожи.
CONFUSABLES = str.maketrans(
    {
        "a": "а",
        "c": "с",
        "e": "е",
        "k": "к",
        "m": "м",
        "o": "о",
        "p": "р",
        "t": "т",
        "x": "х",
        "y": "у",
    }
)

_SEPARATORS = re.compile(r"[\s_\-–—.,;:()\[\]{}/\\]+")


def normalize(text: str) -> str:
    """Приводит синоним к форме для сравнения.

    Регистр, вид пробелов, разделители и похожие латинские буквы различий не
    создают. Пустая строка на выходе означает, что во входе не было ни одного
    значимого символа — вызывающий обязан это отвергнуть.
    """
    # NFKC разворачивает совместимые формы: «м³» → «м3», «№» остаётся, лигатуры
    # раскрываются. Без этого «м³/ч» и «м3/ч» считались бы разными синонимами.
    folded = unicodedata.normalize("NFKC", text).casefold()
    folded = folded.replace("ё", "е").translate(CONFUSABLES)
    return _SEPARATORS.sub(" ", folded).strip()
