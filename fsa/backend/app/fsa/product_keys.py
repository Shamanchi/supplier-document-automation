"""Ключи обозначений изделий: по ним позиция прайса находит свой сертификат.

Поиск по номеру сертификата работает, когда номер уже известен — то есть когда
документ найден и распознан. У позиции прайса номера нет: есть артикул и
наименование. Поэтому нужен второй вход в реестр — по обозначению изделия.

Обозначение приходится добывать из текста: структурные поля `Модель`, `Марка`,
`Артикул` заполнены у 1.8% карточек, а `Полное наименование продукции` — у 99%.
Один сертификат обычно покрывает серию («ОП-2, 3, 4, 5, 6, 8, 10»), поэтому из
одной карточки получается несколько ключей.
"""

from __future__ import annotations

import re

from .normalize import expand_ranges, normalize_designation

# Обозначение изделия: буквенный префикс, дефис, цифро-буквенный хвост —
# «ОП-5(з)-АВСЕ-01», «МПП(Н)-2,5», «МУПТВ-135-ГЗ-ВД».
DESIGNATION = re.compile(
    r"\b[А-ЯA-Z]{2,8}(?:\([^)]{1,12}\))?-[\dА-ЯA-Z][\dА-ЯA-Z,.()\-]{0,24}\b"
)

# Второй вид обозначения — имя собственное с номером исполнения: «Допинг 2.02»,
# «Буран 15». Без него из индекса выпадают изделия, у которых в обозначении нет
# дефиса, а таких в реестре заметная доля.
# Ищется по исходному тексту, а не по приведённому к верхнему регистру: имя
# собственное написано с заглавной («Допинг 2.02», «PYROBEL 21»), а «частотой
# 50 Гц» и «жил 1» — со строчной, и именно регистр их разделяет.
NAMED_MODEL = re.compile(r"\b[А-ЯA-Z][А-Яа-яA-Za-z]{2,15}\s?\d+(?:[.,]\d+)*\b")

# Слова, после которых идёт число, но обозначением это не является: ссылки на
# стандарты, пределы огнестойкости, диапазоны характеристик. Без фильтра в
# индекс попадают «ГОСТ 22233» и «БОЛЕЕ 25» — ключи, под которые сходятся сотни
# карточек и которые ничего не идентифицируют.
NOISE_PREFIXES = frozenset(
    {
        "ГОСТ", "ТУ", "СТО", "СТБ", "ОСТ", "ISO", "IEC", "EN", "ТР", "СП", "СНИП",
        "НПБ", "ГОСТР", "EI", "EIW", "EIS", "REI", "RE",
        "БОЛЕЕ", "МЕНЕЕ", "НЕБОЛЕЕ", "НЕМЕНЕЕ", "ДО", "ОТ", "СВЫШЕ", "ТОЛЩИНОЙ",
        "ДЛИНОЙ", "ШИРИНОЙ", "ВЫСОТОЙ", "МАССОЙ", "НАПРЯЖЕНИЕ", "ДАВЛЕНИЕ",
        "ТЕМПЕРАТУРА", "ДИАМЕТР", "ДИАМЕТРОМ", "РАЗМЕР", "РАЗМЕРОМ",
        "КЛАСС", "ТИП", "ТИПА", "СЕРИЯ", "СЕРИИ", "МОДЕЛЬ", "МОДЕЛИ", "ГРУППА",
        "ТАБЛИЦА", "РИСУНОК", "ПУНКТ", "ПРИЛОЖЕНИЕ", "СТР", "ОКПД", "ТНВЭД",
        "ЕАЭС", "ТС", "RU", "СС", "ДС", "НЕ",
    }
)

# Ключ короче четырёх символов не идентифицирует изделие: «ОП-2» ещё годится,
# «А-1» уже совпадёт с чем угодно.
MIN_KEY_LENGTH = 4

# Колонка и индекс Alembic ограничены 128 символами. Более длинные совпадения
# возникают из текстовых перечней характеристик и не являются устойчивым
# обозначением изделия.
MAX_KEY_LENGTH = 128

# Одна карточка не должна порождать сотни ключей: наименование иногда содержит
# целый перечень исполнений, и весь он в индекс не нужен.
MAX_KEYS_PER_CERTIFICATE = 64

# Список сравнивается в нормализованной форме: в ключах омоглифы уже сведены.
_NOISE_KEYS = frozenset(normalize_designation(word) for word in NOISE_PREFIXES)


def _is_noise(key: str) -> bool:
    """Ключ — ссылка на стандарт или характеристику, а не обозначение изделия."""
    head = re.split(r"[-\s(.]", key, maxsplit=1)[0]
    if not head:
        return True
    # «EIW60» пишут и слитно, поэтому хвостовые цифры с головы снимаются.
    return head in _NOISE_KEYS or re.sub(r"\d+$", "", head) in _NOISE_KEYS


def _looks_like_designation(key: str) -> bool:
    """Обозначение изделия содержит цифру.

    Без этого правила в индекс попадают обычные слова через дефис —
    «приемно-контрольный», «водно-дисперсионные», — под которые сходятся сотни
    карточек и которые не отличают одно изделие от другого.
    """
    return any(character.isdigit() for character in key)


def designations_of(*values: str) -> list[str]:
    """Ключи обозначений из произвольных текстовых полей карточки."""
    found: dict[str, None] = {}
    for value in values:
        if not value:
            continue
        for match in DESIGNATION.finditer(value.upper()):
            _add(found, match.group(0))
        for match in NAMED_MODEL.finditer(value):
            _add(found, match.group(0))
        for item in expand_ranges(value):
            _add(found, item)
        if len(found) >= MAX_KEYS_PER_CERTIFICATE:
            break
    return list(found)[:MAX_KEYS_PER_CERTIFICATE]


def _add(found: dict[str, None], raw: str) -> None:
    key = normalize_designation(raw)
    if (
        MIN_KEY_LENGTH <= len(key) <= MAX_KEY_LENGTH
        and _looks_like_designation(key)
        and not _is_noise(key)
    ):
        found.setdefault(key, None)


def lookup_keys(query: str) -> list[str]:
    """Ключи, по которым искать сертификат для строки прайса.

    Строка прайса — это не только обозначение: «Огнетушитель ОП-5(з) АВСЕ, 5 кг»
    содержит и тип, и массу. Поэтому из неё достаются те же обозначения, а если
    не нашлось ни одного — вся строка нормализуется целиком: короткий артикул
    вроде `МГПХ` не подходит под шаблон, но искать по нему всё равно надо.
    """
    keys = designations_of(query)
    if keys:
        return keys
    key = normalize_designation(query)
    if not MIN_KEY_LENGTH <= len(key) <= MAX_KEY_LENGTH or _is_noise(key):
        return []
    return [key]
